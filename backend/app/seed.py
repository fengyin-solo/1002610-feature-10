"""示例数据：每个模块给几条不同状态的记录，方便起服务后立刻看到内容。"""
from __future__ import annotations

from datetime import date, timedelta
from typing import Any

# 质量监察示例数据围绕「今天」排时间，保证起服务就能看到逾期、待整改、已闭合。
_today = date.today()


def _day(offset: int) -> str:
    return (_today + timedelta(days=offset)).strftime("%Y-%m-%d")


_DATE_PLACEHOLDERS = {
    "d0": _day(0),       # 今天
    "dm1": _day(-1),     # 昨天
    "dm2": _day(-2),
    "dm3": _day(-3),
    "dm4": _day(-4),
    "dm5": _day(-5),
    "dm6": _day(-6),
    "dm7": _day(-7),
    "dm8": _day(-8),
    "dm9": _day(-9),
    "dm10": _day(-10),
    "dp3": _day(3),      # 未来的整改期限
    "dp5": _day(5),
}


def _qc(
    entry_id: int,
    status: str,
    pending: bool,
    abnormal: bool,
    *,
    code: str,
    day: str,
    area: str,
    matter: str,
    violation: str,
    clause: str,
    requirement: str,
    deadline: str,
    fixer: str,
    fix_note: str,
    nodes: list[tuple[str, str, str, str]],
) -> dict[str, Any]:
    """构造一条带时间轴节点的质量监察示例记录。"""
    return {
        'id': entry_id,
        'status': status,
        'pending': pending,
        'abnormal': abnormal,
        'overdue': False,
        '监察编号': code,
        '监察日期': day,
        '监察区域': area,
        '监察事项': matter,
        '发现违章': violation,
        '违章条款': clause,
        '整改要求': requirement,
        '整改期限': deadline,
        '整改人': fixer,
        '整改情况': fix_note,
        'timeline': [
            {'action': action, 'actor': actor, 'time': moment, 'note': note}
            for action, actor, note, moment in nodes
        ],
    }


def _resolve_placeholders(value: Any) -> Any:
    """把 {dm5} 这类日期占位符替换成实际日期，节点时间里带时分也能替换。"""
    if isinstance(value, str):
        for key, day in _DATE_PLACEHOLDERS.items():
            value = value.replace('{' + key + '}', day)
        return value
    if isinstance(value, list):
        return [_resolve_placeholders(item) for item in value]
    if isinstance(value, dict):
        return {key: _resolve_placeholders(item) for key, item in value.items()}
    return value


